/**
 * @brief Prints all coefficients of a polynomial
 * 
 * @param p Pointer to the poly structure
 */
void print_poly(const poly *p, size_t len) {
    size_t i;
    for (i = 0; i < len; i++) {
        print_u32(i);
        print_string(":\t0x");
        print_u32((uint32_t)p->coeffs[i]);
        print_string("\n");
    }
}


int pasta_init(void) {
    int i;

    print_string("\n pasta_simple Init Test\n");

    for (i = 0; i < PASTA_KEY_SIZE; i++) {
        pasta_key[i] = TEST_PRIVATE_KEY[i];
    }

    for (i = 0; i < N; i++) {
        state1[i] = 0;
        state2[i] = 0;
    }

    /* ---------- SHAKE buffer state ---------- */
    for (i = 0; i < sizeof(shake_buf); i++) {
        shake_buf[i] = 0;
    }
    shake_pos = 0;

    return 0;
}

