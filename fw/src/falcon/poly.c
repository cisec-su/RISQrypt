void poly_init_q() {
    const uint32_t q = (Q << 16) | Q;
    const uint32_t mu[2] = {0xe425e9e0, 0x55538};
    ntt_lite_load_q(q, mu, FALCON_LOG_N - 1, LOG_Q, 0, NTT_LITE_MODE_POLY);
}


void poly_init_ntt() {
    ntt_lite_load_twiddle((uint32_t*) psi);
}


void poly_init_invntt() {
    const uint32_t inv2 = (INV2 << 16) | INV2;
    ntt_lite_set_inv2(inv2);
    ntt_lite_load_twiddle((uint32_t*) psi_inv);
}


void poly_ntt(poly *a) {
    ntt_lite_forward_ntt((uint32_t*) a->coeffs, (uint32_t*) a->coeffs);
}


void poly_ntt_from_center(poly *a, const poly *b) {
    ntt_lite_set_bound(((Q >> 1) << 16) | (Q >> 1));
    ntt_lite_fromcenter(NTT_LITE_OUTPUT_DIS, (uint32_t*) b->coeffs);
    ntt_lite_forward_ntt((uint32_t*) a->coeffs, NTT_LITE_INPUT_DIS);
}


void poly_invntt_sub(poly *a, const poly *b) {
    ntt_lite_backward_ntt(NTT_LITE_OUTPUT_DIS, (uint32_t*) a->coeffs);
    ntt_lite_sub((uint32_t*) a->coeffs, NTT_LITE_INPUT_DIS, (uint32_t*) b->coeffs);
}


void poly_basemul(poly *r, const poly *a, const poly *b)
{
    ntt_lite_set_ctrl(FALCON_LOG_N - 2, 14, NTT_LITE_MODE_POLY);
    ntt_lite_load_zeta((uint32_t*) zetas);
    ntt_lite_pwm((uint32_t*) r->coeffs, (uint32_t*) a->coeffs, (uint32_t*) b->coeffs);
    ntt_lite_load_zeta((uint32_t*) zetas + 128);
    ntt_lite_pwm((uint32_t*) r->coeffs + 128, (uint32_t*) a->coeffs + 128, (uint32_t*) b->coeffs + 128);
    ntt_lite_set_ctrl(FALCON_LOG_N - 1, 14, NTT_LITE_MODE_POLY);
}


