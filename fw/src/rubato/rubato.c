/**
 * @brief Applies RUBATO Feistel S-box layer.
 * @param B Output polynomial.
 * @param A Input polynomial.
 */
void rubato_sbox_feistel(poly *B, const poly *A) {
    uint32_t C[N+1];
    poly src;

    memcpy(src.coeffs, A->coeffs, N * sizeof(int32_t));
    C[0] = 0x00000;
    memcpy(C + 1, src.coeffs, N * sizeof(uint32_t));
    ntt_lite_pwm(NTT_LITE_OUTPUT_DIS, C, C);
    ntt_lite_add(B->coeffs, NTT_LITE_INPUT_DIS, src.coeffs);
}

/**
 * @brief Applies RUBATO linear layer A = M * B * M_transpoze over Z_q.
 * @param A Output polynomial.
 * @param B Input polynomial.
 */
void rubato_linear_layer(poly *A, const poly *B) {
    size_t i;
    poly src;

    ntt_lite_set_bound(0);
    ntt_lite_add_const(src.coeffs, B->coeffs);  // src = B (ntt_lite_add_const just copies with type conversion)

    for (i = 0; i < N; i++) {
        ntt_lite_pwm(NTT_LITE_OUTPUT_DIS, (uint32_t*)src.coeffs, (uint32_t*)K[i].coeffs);
        ntt_lite_sum((uint32_t *)&A->coeffs[i], NTT_LITE_INPUT_DIS);
    }

}


/**
 * @brief Generates one RUBATO keystream block.
 * @param ciphertext Output polynomial.
 * @param plaintext  Input polynomial to XOR with the keystream.
 * @param key        Secret key polynomial.
 * @param nonce      64-bit nonce.
 * @param block_ctr  64-bit block counter.
 */
void rubato_encrypt(poly *ciphertext, const poly *plaintext, poly *key, uint64_t nonce, uint64_t block_ctr){

    poly state;
    poly rnd;
    size_t r;
    static const int32_t state_init[N] = RUBATO_STATE_INIT;

    poly_init_q();

    ntt_lite_set_bound(0);
    ntt_lite_add_const(state.coeffs, state_init);

    for (r = 0; r < (size_t) RUBATO_R; r++) {
        poly_uniform(&rnd, nonce, block_ctr, r);
        poly_mult_add(&state, &rnd, key, &state);
        rubato_linear_layer(&state, &state);
        rubato_sbox_feistel(&state, &state);
    }
    rubato_linear_layer(&state, &state);

    poly_uniform(&rnd, nonce, block_ctr, RUBATO_R);
    ntt_lite_pwm(NTT_LITE_OUTPUT_DIS, key->coeffs, rnd.coeffs);
    ntt_lite_add(NTT_LITE_OUTPUT_DIS, NTT_LITE_INPUT_DIS, state.coeffs);
    ntt_lite_add(ciphertext->coeffs, NTT_LITE_INPUT_DIS, plaintext->coeffs);
}

/*
 * @brief Generate constant key, nonce and block counter values for tests
 * @param key[out]        buffer of N coefficients (int32_t) to receive the key
 * @param nonce[out]      pointer to receive the nonce value (may be NULL)
 * @param block_ctr[out]  pointer to receive the block counter (may be NULL)
 *
 * The values returned are fixed constants defined in the implementation.
 */
void rubato_key_gen(poly *key, uint64_t *nonce, uint64_t *block_ctr){
    size_t i;

    if (key != NULL) {
        for (i = 0; i < N; i++) {
            key->coeffs[i] = 1;
        }
    }

    if (nonce != NULL) {
        *nonce = 0x123456789ULL;
    }
    if (block_ctr != NULL) {
        *block_ctr = 0x0ULL;
    }
}
